def mask(text):
    """The string as rows of booleans at font-pixel resolution, one blank column between glyphs."""
    rows = [''] * 7
    for i, ch in enumerate(text):
        g = GLYPHS[ch]
        for r in range(7):
            rows[r] += g[r] + ('.' if i < len(text) - 1 else '')
    return [[c == '#' for c in row] for row in rows]


def draw(img, text, cx, y, scale, color, outline=(18, 14, 12)):
    """Draws `text` centred on x = cx with its top at y."""
    m = mask(text)
    h, w = len(m), len(m[0])
    x0 = cx - (w * scale) // 2
    px = img.load()

    def block(fx, fy, col):
        for yy in range(y + fy * scale, y + (fy + 1) * scale):
            for xx in range(x0 + fx * scale, x0 + (fx + 1) * scale):
                if 0 <= xx < img.width and 0 <= yy < img.height:
                    px[xx, yy] = col

    for fy in range(-1, h + 1):
        for fx in range(-1, w + 1):
            if any(0 <= fy + dy < h and 0 <= fx + dx < w and m[fy + dy][fx + dx] for dy in (-1, 0, 1) for dx in (-1, 0, 1)):
                block(fx, fy, outline)
    for fy in range(h):
        for fx in range(w):
            if m[fy][fx]:
                block(fx, fy, color)
